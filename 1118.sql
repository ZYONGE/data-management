SELECT   POSITION, ROUND(AVG(HEIGHT), 2) 평균키
FROM     PLAYER
GROUP BY POSITION
HAVING   MAX(HEIGHT) >= 190;


-- 2.
SELECT   D.DNAME     AS 부서명,
         E.JOB       AS 직무,
         COUNT(*)    AS 직원수,
         SUM(E.SAL)  AS 급여합계,
         AVG(E.SAL)  AS 평균급여
FROM     EMP E
         JOIN DEPT D ON E.DEPTNO = D.DEPTNO
GROUP BY D.DNAME, E.JOB
HAVING   AVG(E.SAL) > 2000
ORDER BY D.DNAME ASC, E.JOB ASC;


